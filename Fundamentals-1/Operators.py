#arithmetic operators

a = 10
b = 5

print(a+b) #addition
print(a-b) #subtraction
print(a*b) #multiplication
print(a/b) #division
print(a%b) #modulus
print(a**b) #exponentiation

#comparison operators

c = 50
d = 20

print(c == d) #False
print(c != d) #True
print(c > d) #True
print(c < d) #False
print(c >= d) #True
print(c <= d) #False

#assignment operators

num = 10
num = num + 10 #10+10 = 20
#num += 10
print("Num :",num)

#logical operators

print(not False)
print(not True)

